/**
 * Build the operator-override block — the operator's `systemPrompt` wrapped in
 * an explicit "ABSOLUTE PRIORITY" boundary. The engine places this AT THE END
 * of the layered system message (just before the JSON envelope) so the LLM
 * treats it as the final, highest-priority instruction. Earlier rules in the
 * persona, catalog, collection-prompt, or generic norms LOSE on conflict.
 */
export function buildOperatorOverrideBlock(operatorPrompt: string | null | undefined): string {
  const op = (operatorPrompt ?? '').trim();
  if (!op) return '';
  return [
    '',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    '🚨 توجيهات المالك — الأولوية المطلقة',
    'هذه الأوامر تعلو على كل ما سبق في هذه الرسالة.',
    'إذا تعارضت مع أي قاعدة سابقة (شخصية، أطر، كتالوج، تجميع، قواعد افتراضية)،',
    'اتبع هذه فقط ولا تشكك. هي قواعد لا تقبل الرفض.',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    op,
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
  ].join('\n');
}

/**
 * Build the customer-stage hint — a one-liner inserted into the prompt that
 * tells the LLM what play to pick from the script.
 */
export function buildStageHint(stage: 'sent_no_reply' | 'replied' | 'ordered' | null): string {
  if (!stage) return `🚦 STAGE=first_contact — هذا أول تواصل. ابدأ بـ Hook + AIDA Attention. لا تطرح سؤال شخصي مباشرة.`;
  if (stage === 'sent_no_reply') return `🚦 STAGE=sent_no_reply — العميل ما رد علينا بعد. أعد التشغيل بلطف بإضافة قيمة جديدة. بدون لوم.`;
  if (stage === 'replied') return `🚦 STAGE=replied — العميل تفاعل. استمر بـ AIDA Interest/Desire.`;
  return `🚦 STAGE=ordered — العميل أكد طلب. شكر دافئ + Cross-sell خفيف إذا مناسب.`;
}

/**
 * Legacy single-shot composite (kept for backward compat with callers that
 * don't yet use the layered assembly). Now uses the same boundary as the
 * engine path so behavior is consistent everywhere.
 */
export function buildSystemPrompt(operatorPrompt: string): string {
  const override = buildOperatorOverrideBlock(operatorPrompt);
  if (!override) return AI_SALES_SCRIPT_AR;
  return `${AI_SALES_SCRIPT_AR}\n${override}`;
}
